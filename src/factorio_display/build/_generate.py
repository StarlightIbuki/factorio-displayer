"""Build-time resource generation — computes signal pool, its hash, and the
display-unit blueprint so they can be baked into the package at build time."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any


def generate_resources(config_path: str = "config.toml") -> dict[str, Any]:
    """Compute and return all build-time resources.

    Returns a dict with keys ``pool_hash``, ``display_blueprint``, and ``pool``.
    """
    from ..integer2signal.config_loader import load_config
    from ..integer2signal.pool import get_filtered_pool
    from ..integer2signal.mapping import SignalMapping

    config = load_config(config_path)
    pool: list[str] = get_filtered_pool(config["reserved"]["clock_signal"])
    mapping = SignalMapping(config, pool)

    # ---- hash the signal pool (deterministic) --------------------------------
    pool_hash = hashlib.sha256(
        json.dumps(pool, sort_keys=True).encode()
    ).hexdigest()

    # ---- build the display-unit blueprint -----------------------------------
    from draftsman.blueprintable import Blueprint
    from draftsman.entity import new_entity

    w, h = config["display"]["width"], config["display"]["height"]
    hole_tl = tuple(config["display"]["hole_top_left"])
    hole_br = tuple(config["display"]["hole_bottom_right"])

    blueprint = Blueprint()
    blueprint.label = f"{w}x{h} Display Unit (2.0 RGB)"

    lamp_grid: list[list[str | None]] = [
        [None for _ in range(w)] for _ in range(h)
    ]

    for (x, y), sig in mapping.iter_pixels():
        lamp_id = f"lamp_{x}_{y}"
        lamp = new_entity("small-lamp", id=lamp_id, tile_position=(x, y))
        lamp.always_on = True
        lamp.circuit_enable_disable = False
        lamp.use_colors = True
        lamp.color_mode = 2
        lamp.rgb_signal = {"name": sig["name"], "quality": sig["quality"]}
        blueprint.entities.append(lamp)
        lamp_grid[y][x] = lamp_id

    blueprint.entities.append(
        new_entity(
            "substation",
            id="substation_main",
            tile_position=(hole_tl[0], hole_tl[1]),
            quality="legendary",
        )
    )

    # Horizontal wiring — chain lamps across each row, skipping holes
    for y in range(h):
        for x in range(w - 1):
            curr_id = lamp_grid[y][x]
            next_x = x + 1
            while next_x < w and lamp_grid[y][next_x] is None:
                next_x += 1
            if next_x < w and curr_id:
                blueprint.add_circuit_connection("red", curr_id, lamp_grid[y][next_x])

    # Vertical wiring at the rightmost column
    for y in range(h - 1):
        if lamp_grid[y][w - 1] and lamp_grid[y + 1][w - 1]:
            blueprint.add_circuit_connection(
                "red", lamp_grid[y][w - 1], lamp_grid[y + 1][w - 1]
            )

    display_blueprint: str = blueprint.to_string()

    # Export manifest for consumers (encoder, external tools)
    mapping.export_manifest()

    return {
        "pool_hash": pool_hash,
        "display_blueprint": display_blueprint,
        "pool": pool,
    }


def write_generated_module(
    output_path: Path,
    resources: dict[str, Any],
    version: str,
) -> None:
    """Write ``_generated.py`` with the baked-in constants."""
    short_hash = resources["pool_hash"][:8]
    full_version = f"{version}+{short_hash}"

    # Escape the blueprint string safely for a Python source file
    bp_escaped = resources["display_blueprint"].replace("\\", "\\\\").replace('"""', '\\"\\"\\"')

    content = f'''\
"""Auto-generated by the build hook — do not edit manually.

Pool hash : {resources["pool_hash"]}
Version   : {full_version}
"""

POOL_HASH = "{resources["pool_hash"]}"
"""SHA-256 hex digest of the sorted signal-pool list."""

DISPLAY_BLUEPRINT = """\\
{bp_escaped}\
"""
"""Pre-computed display-unit blueprint string."""

VERSION = "{full_version}"
"""Package version including the pool-hash short-id."""
'''
    output_path.write_text(content, encoding="utf-8")
