"""Build-time resource generation — computes signal pool, its hash, and the
display-unit blueprint so they can be baked into the package at build time."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any


def generate_resources(config_path: str = "config.toml") -> dict[str, Any]:  # pylint: disable=too-many-locals
    """Compute and return all build-time resources.

    Returns a dict with keys ``pool_hash``, ``pool``, ``display_width``, etc."""
    from ..integer2signal.config_loader import load_config  # pylint: disable=import-outside-toplevel
    from ..integer2signal.pool import get_filtered_pool  # pylint: disable=import-outside-toplevel
    from ..integer2signal.mapping import SignalMapping  # pylint: disable=import-outside-toplevel

    config = load_config(config_path)
    pool: list[str] = get_filtered_pool(config["reserved"]["clock_signal"])

    # ---- extract all config values to bake into the wheel -----------------
    display_width: int = config["display"]["width"]
    display_height: int = config["display"]["height"]
    qualities: list[str] = config["signals"]["qualities"]
    clock_signal: str = config["reserved"]["clock_signal"]
    loudness_signal: str = config["reserved"]["loudness_signal"]

    mapping = SignalMapping(
        display_width, display_height, qualities, pool,
    )
    base_signals: list[str] = mapping.base_signals

    # ---- hash the signal pool (deterministic) --------------------------------
    pool_hash = hashlib.sha256(
        json.dumps(pool, sort_keys=True).encode()
    ).hexdigest()

    # Export manifest for consumers (encoder, external tools)
    mapping.export_manifest()

    return {
        "pool_hash": pool_hash,
        "pool": pool,
        "display_width": display_width,
        "display_height": display_height,
        "qualities": qualities,
        "clock_signal": clock_signal,
        "loudness_signal": loudness_signal,
        "base_signals": base_signals,
    }


def write_generated_module(
    output_path: Path,
    resources: dict[str, Any],
    version: str,
) -> None:
    """Write ``_generated.py`` with the baked-in constants."""
    short_hash = resources["pool_hash"][:8]
    full_version = f"{version}+{short_hash}"

    # Format base_signals as a Python list literal
    base_signals_repr = repr(resources["base_signals"])

    content = f'''\
"""Auto-generated by the build hook - do not edit manually.

Pool hash : {resources["pool_hash"]}
Version   : {full_version}
"""

POOL_HASH = "{resources["pool_hash"]}"
"""SHA-256 hex digest of the sorted signal-pool list."""

VERSION = "{full_version}"
"""Package version including the pool-hash short-id."""

DISPLAY_WIDTH: int = {resources["display_width"]}
"""Display grid width in tiles (from config.toml)."""

DISPLAY_HEIGHT: int = {resources["display_height"]}
"""Display grid height in tiles (from config.toml)."""

QUALITIES: list[str] = {resources["qualities"]!r}
"""Space Age quality tiers used for signal multiplexing (from config.toml)."""

CLOCK_SIGNAL: str = "{resources["clock_signal"]}"
"""Reserved signal name for global frame-sync clock (from config.toml)."""

LOUDNESS_SIGNAL: str = "{resources["loudness_signal"]}"
"""Reserved signal name for audio loudness (from config.toml)."""

SIGNAL_POOL: list[str] = {base_signals_repr}
"""Base signal names assigned to display pixels (derived from config.toml + Factorio data)."""
'''
    output_path.write_text(content, encoding="utf-8")
